/**
 * 簡體中文逐字轉換為繁體中文（用於沒有官方翻譯的文字）
 * 採用逐字元映射，避免多字元替換的順序問題
 */
export function s2t(text: string): string {
  if (!text) return text;
  let result = '';
  for (const ch of text) {
    result += S2T_MAP[ch] || ch;
  }
  return result;
}

