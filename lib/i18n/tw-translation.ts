/**
 * 將簡體中文轉換為繁體中文（用於沒有官方翻譯的文字）
 */
export function simplifiedToTw(text: string): string {
  let result = text;
  for (const [simp, trad] of Object.entries(simplifiedToTraditional)) {
    result = result.replaceAll(simp, trad);
  }
  return result;
}
