/**
 * 取得分類的繁中名稱。
 * @param categoryId ItemUICategory 的 row id
 * @param fallbackEn 查無繁中時使用的英文名稱（來自 items.msgpack）
 */
export function getCategoryNameTw(categoryId: number, fallbackEn = ''): string {
  return CATEGORY_NAMES_TW[categoryId] || fallbackEn || `分類 ${categoryId}`;
}

/** 是否已收錄繁中名稱 */
export function hasCategoryNameTw(categoryId: number): boolean {
  return categoryId in CATEGORY_NAMES_TW;
}
